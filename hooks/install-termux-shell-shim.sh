#!/usr/bin/env bash
# Termux-only: give Claude Code a shell whose children can run shebang scripts.
#
# Why this exists, in short: the Claude Code binary is glibc, so its launcher
# must unset LD_PRELOAD or the bionic termux-exec/libtagfix preloads get
# inherited by a glibc process and it dies with
#
#     error while loading shared libraries: libdl.so: cannot open shared object
#
# But that same preload is what rewrites shebangs, and Claude Code's Bash tool
# spawns a HARDCODED /bin/bash, which Termux does not have. Without the shim,
# any script starting #!/usr/bin/env ... or #!/bin/bash fails:
#
#     /usr/bin/env: bad interpreter: No such file or directory   (exit 126)
#
# That breaks npx, pip entry points, git hooks, and most project scripts.
#
# The fix is a small shell that puts the preload back and hands off. Claude
# Code's shell detection accepts any path containing "bash" or "zsh" that
# passes a --version check, so CLAUDE_CODE_SHELL is enough to select it.
#
# See docs/claude-code-transcript-format.md §11.
set -u

PREFIX="${PREFIX:-/data/data/com.termux/files/usr}"
PRELOAD="$PREFIX/lib/libtermux-exec-ld-preload.so"
BIN_DIR="${CLAUDE_SHIM_DIR:-$HOME/.local/share/claude/bin}"
SHIM="$BIN_DIR/bash"

if [ ! -f "$PRELOAD" ]; then
  echo "install-termux-shell-shim: $PRELOAD not found — is termux-exec installed?" >&2
  exit 1
fi

mkdir -p "$BIN_DIR"
cat > "$SHIM" <<EOF
#!$PREFIX/bin/bash
# Generated by agent-session-bridge. Restores Termux's exec interceptor for
# shells started by the glibc Claude Code binary, so shebangs resolve.
export LD_PRELOAD="$PRELOAD"
exec $PREFIX/bin/bash "\$@"
EOF
chmod +x "$SHIM"

echo "installed: $SHIM"
echo
echo "Point Claude Code at it by exporting:"
echo "    export CLAUDE_CODE_SHELL=$SHIM"
echo
echo "or add it to ~/.claude/settings.json:"
echo "    { \"env\": { \"CLAUDE_CODE_SHELL\": \"$SHIM\" } }"
echo
echo "Verify with a script that uses an env shebang:"
echo "    printf '#!/usr/bin/env bash\\necho OK\\n' > /tmp/t.sh && chmod +x /tmp/t.sh"
echo "    # then ask Claude Code to run /tmp/t.sh through its Bash tool"
